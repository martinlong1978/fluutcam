//! The generated pages of the user wiki (`docs/wiki/`): one page per
//! toolpath type with every setting, and the list of diagnostics.
//!
//! ```text
//! cargo xtask wiki-reference            # write the pages
//! cargo xtask wiki-reference --check    # fail when a page is out of date
//! ```
//!
//! Sources:
//! - the D15 field tables of this crate (`ToolpathTypeId::fields`): key,
//!   unit, default, group;
//! - the Fluent catalogs of `fluut-i18n` (`crates/fluut-i18n/locales/en`):
//!   type and setting labels, diagnostic messages;
//! - `docs/design/D15*.md`: the description of each type, the range and
//!   dependencies of each setting, and the severity and rule of each
//!   diagnostic code;
//! - `docs/wiki/reference/help.toml` (what a setting does) and
//!   `docs/wiki/reference/advice.toml` (what to do about a diagnostic),
//!   written by hand;
//! - the `Diagnostic::error` and `Diagnostic::warning` calls in
//!   `crates/*/src` (the code and the message), found by scanning the text.
//!
//! The pages carry a first line saying they are generated.

use fluut_model::ToolpathTypeId;
use fluut_model::params::{ConstVal, DefaultRule, FieldKind, FieldMeta, Group, HEIGHT_REFS};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

/// First line of every generated page.
const MARK: &str = "<!-- Generated by `cargo xtask wiki-reference`. Do not edit this page: change the generator, `reference/help.toml` or `reference/advice.toml`. -->";

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn read(p: &Path) -> String {
    std::fs::read_to_string(p).unwrap_or_else(|e| panic!("cannot read {}: {e}", p.display()))
}

// ── Fluent catalogs ─────────────────────────────────────────────────

/// `id = value` lines of the English catalogs (single-line messages).
fn catalog() -> BTreeMap<String, String> {
    let dir = root().join("crates/fluut-i18n/locales/en");
    let mut out = BTreeMap::new();
    for f in ["app.ftl", "ops.ftl", "params.ftl", "diagnostics.ftl"] {
        for line in read(&dir.join(f)).lines() {
            if line.starts_with('#') || line.starts_with(' ') {
                continue;
            }
            if let Some((k, v)) = line.split_once(" = ") {
                out.insert(k.trim().to_owned(), v.trim().to_owned());
            }
        }
    }
    out
}

/// A key in words, as the application labels a setting without a message.
fn words(key: &str) -> String {
    let key = key.strip_suffix("_deg").unwrap_or(key);
    let mut s = key.replace('_', " ");
    if let Some(c) = s.get(..1) {
        let up = c.to_uppercase();
        s.replace_range(..1, &up);
    }
    s
}

// ── Markdown tables of the design documents ─────────────────────────

/// One table row with the section it is in.
#[derive(Clone, Debug)]
struct Row {
    /// Heading of the section (without the `#`s).
    heading: String,
    header: Vec<String>,
    cells: Vec<String>,
}

impl Row {
    fn get(&self, col: &str) -> Option<&str> {
        let i = self.header.iter().position(|h| h == col)?;
        self.cells.get(i).map(String::as_str)
    }
}

fn cells(line: &str) -> Vec<String> {
    let t = line.trim().trim_start_matches('|').trim_end_matches('|');
    t.replace("\\|", "\u{1}")
        .split('|')
        .map(|c| c.trim().replace('\u{1}', "|"))
        .collect()
}

fn unbacktick(s: &str) -> String {
    s.trim().trim_matches('`').to_owned()
}

/// Every table row of a document, with its header and nearest heading.
fn table_rows(md: &str) -> Vec<Row> {
    let mut rows = Vec::new();
    let mut heading = String::new();
    let mut header: Option<Vec<String>> = None;
    let mut in_code = false;
    for line in md.lines() {
        if line.starts_with("```") {
            in_code = !in_code;
        }
        if in_code {
            continue;
        }
        if line.starts_with('#') {
            heading = line.trim_start_matches('#').trim().to_owned();
            header = None;
        } else if line.trim_start().starts_with('|') {
            let c = cells(line);
            if c.iter()
                .all(|x| x.chars().all(|ch| ch == '-' || ch == ':' || ch == ' '))
            {
                continue;
            }
            match &header {
                None => header = Some(c),
                Some(h) => rows.push(Row {
                    heading: heading.clone(),
                    header: h.clone(),
                    cells: c,
                }),
            }
        } else {
            header = None;
        }
    }
    rows
}

/// A heading of the form `### 2.1 `id`` (a number, then the id).
fn names_type(heading: &str, needle: &str) -> bool {
    let h = heading.trim_start_matches('#').trim();
    match h.split_once(' ') {
        Some((num, rest)) => {
            num.chars().all(|c| c.is_ascii_digit() || c == '.') && rest.trim().starts_with(needle)
        }
        None => false,
    }
}

/// The text of a type's section: from the heading naming `` `type_id` `` to
/// the next heading of the same or a higher level.
fn type_section<'a>(md: &'a str, id: &str) -> Option<&'a str> {
    let needle = format!("`{id}`");
    let mut start = None;
    let mut level = 0;
    let mut offset = 0;
    for line in md.split_inclusive('\n') {
        if line.starts_with('#') {
            let l = line.chars().take_while(|c| *c == '#').count();
            if let Some(s) = start {
                if l <= level {
                    return Some(&md[s..offset]);
                }
            } else if names_type(line, &needle) && l <= 3 {
                start = Some(offset);
                level = l;
            }
        }
        offset += line.len();
    }
    start.map(|s| &md[s..])
}

/// Removes design-document references: `[S 03 §3.10.4]` and `(D09 §2.4)`.
fn strip_refs(s: &str) -> String {
    let mut out = String::new();
    let mut rest = s;
    loop {
        let a = rest.find("[S ");
        let b = rest.find("(D");
        let next = match (a, b) {
            (Some(a), Some(b)) => Some((a.min(b), a < b)),
            (Some(a), None) => Some((a, true)),
            (None, Some(b)) => Some((b, false)),
            (None, None) => None,
        };
        let Some((i, square)) = next else {
            out.push_str(rest);
            break;
        };
        let close = if square { ']' } else { ')' };
        let looks_like_ref = if square {
            true
        } else {
            rest[i + 2..]
                .chars()
                .next()
                .is_some_and(|c| c.is_ascii_digit())
        };
        match rest[i..].find(close) {
            Some(j) if looks_like_ref => {
                out.push_str(rest[..i].trim_end());
                rest = &rest[i + j + 1..];
            }
            _ => {
                out.push_str(&rest[..=i]);
                rest = &rest[i + 1..];
            }
        }
    }
    out.replace(" .", ".")
        .replace(" ,", ",")
        .replace(",)", ")")
        .replace("  ", " ")
}

/// First paragraph of a section, after its heading, without references.
fn first_paragraph(section: &str) -> String {
    let mut para = Vec::new();
    for line in section.lines().skip(1) {
        let t = line.trim();
        if t.is_empty() {
            if para.is_empty() {
                continue;
            }
            break;
        }
        if t.starts_with('#') || t.starts_with('|') || t.starts_with("```") || t.starts_with('-') {
            if para.is_empty() {
                continue;
            }
            break;
        }
        para.push(t);
    }
    strip_refs(&para.join(" "))
}

// ── Hand-written text ────────────────────────────────────────────────

fn toml_table(p: &Path) -> toml::Table {
    read(p)
        .parse()
        .unwrap_or_else(|e| panic!("{}: {e}", p.display()))
}

struct Texts {
    /// `path` or `type.path` → what the setting does.
    help: BTreeMap<String, String>,
    /// `(match, text)`; a match ending in `*` is a prefix.
    advice: Vec<(String, String)>,
    /// Type id → plain description of the type.
    description: BTreeMap<String, String>,
}

fn texts() -> Texts {
    let dir = root().join("docs/wiki/reference");
    let help_file = toml_table(&dir.join("help.toml"));
    let help = help_file
        .get("help")
        .and_then(toml::Value::as_table)
        .map(|t| {
            t.iter()
                .filter_map(|(k, v)| v.as_str().map(|s| (k.clone(), s.to_owned())))
                .collect()
        })
        .unwrap_or_default();
    let advice = toml_table(&dir.join("advice.toml"));
    let advice = advice
        .get("advice")
        .and_then(toml::Value::as_array)
        .map(|a| {
            a.iter()
                .filter_map(|e| {
                    Some((
                        e.get("match")?.as_str()?.to_owned(),
                        e.get("text")?.as_str()?.to_owned(),
                    ))
                })
                .collect()
        })
        .unwrap_or_default();
    let description = help_file
        .get("description")
        .and_then(toml::Value::as_table)
        .map(|t| {
            t.iter()
                .filter_map(|(k, v)| v.as_str().map(|s| (k.clone(), s.to_owned())))
                .collect()
        })
        .unwrap_or_default();
    Texts {
        help,
        advice,
        description,
    }
}

impl Texts {
    fn advice_for(&self, code: &str) -> Option<&str> {
        let mut best: Option<(usize, &str)> = None;
        for (m, t) in &self.advice {
            let hit = match m.strip_suffix('*') {
                Some(p) => code.starts_with(p),
                None => m == code,
            };
            if hit && best.is_none_or(|(l, _)| m.len() > l) {
                best = Some((m.len(), t));
            }
        }
        best.map(|(_, t)| t)
    }
}

// ── Toolpath type pages ─────────────────────────────────────────────

fn category(t: ToolpathTypeId) -> &'static str {
    use ToolpathTypeId::*;
    match t {
        Contour2d | Pocket2d | Face | Trace | Chamfer2d | Bore | OptimisedLoad2d | Engrave => "2-D",
        Drill => "Holes",
        OptimisedLoad3d | Pocket3d => "3-D roughing",
        Parallel | Contour | Horizontal | Spiral | Scallop | SteepAndShallow => "3-D finishing",
        RotaryRough | RotaryAlongX | RotaryAroundA | RotarySpiral => "Rotary",
        ManualNc => "Utility",
    }
}

fn setup_kinds(t: ToolpathTypeId) -> &'static str {
    if t.is_rotary() {
        "rotary"
    } else {
        "three_axis, indexed"
    }
}

fn page_name(t: ToolpathTypeId) -> String {
    format!("Toolpath-{}", t.as_str().replace('_', "-"))
}

fn num(v: f64) -> String {
    if v == v.trunc() && v.abs() < 1e12 {
        format!("{v:.0}")
    } else {
        format!("{v}")
    }
}

fn unit(kind: FieldKind) -> String {
    match kind {
        FieldKind::Length => "mm".into(),
        FieldKind::Feed => "mm/min".into(),
        FieldKind::Speed => "rev/min".into(),
        FieldKind::Angle => "degrees".into(),
        FieldKind::Duration => "seconds".into(),
        FieldKind::Count => "count".into(),
        FieldKind::Bool => "yes or no".into(),
        FieldKind::Enum(o) => o
            .iter()
            .map(|x| format!("`{x}`"))
            .collect::<Vec<_>>()
            .join(", "),
        FieldKind::Height => "height: a `ref` and an `offset` in mm".into(),
        FieldKind::XPos => "position along X: `ref` and `offset` in mm".into(),
        FieldKind::Text => "text".into(),
        FieldKind::Selection => "selection of bodies, faces or edges".into(),
        FieldKind::Point => "point `[x, y, z]` in mm".into(),
        FieldKind::Points => "list of points in mm".into(),
        FieldKind::Table(_) => "group of settings (below)".into(),
    }
}

fn default_text(d: DefaultRule) -> String {
    match d {
        DefaultRule::None => "not set".into(),
        DefaultRule::Const(ConstVal::Num(v)) => num(v),
        DefaultRule::Const(ConstVal::Bool(b)) => if b { "yes" } else { "no" }.into(),
        DefaultRule::Const(ConstVal::Str(s)) => format!("`{s}`"),
        DefaultRule::Const(ConstVal::Height(r, o)) => {
            if o == 0.0 {
                format!("`{r}`")
            } else {
                format!("`{r}` {} {}", if o < 0.0 { "-" } else { "+" }, num(o.abs()))
            }
        }
        DefaultRule::FromTool(k) => format!("from the tool's cutting data (`{k}`)"),
        DefaultRule::Computed(t) => format!("calculated from {t}"),
    }
}

/// A field and its path in the group (`feed.cut`).
fn flatten(group_fields: &[&'static FieldMeta]) -> Vec<(String, &'static FieldMeta)> {
    let mut out = Vec::new();
    for f in group_fields {
        out.push((f.key.to_owned(), *f));
        for s in f.sub_fields() {
            out.push((format!("{}.{}", f.key, s.key), s));
        }
    }
    out
}

fn cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

/// Rows of the D15 documents by type: `(group key, key)` of the common
/// tables, and the key of the type's own tables.
struct Docs {
    d15: String,
    d15b: String,
    common: BTreeMap<(String, String), Row>,
}

fn docs() -> Docs {
    let dir = root().join("docs/design");
    let d15 = read(&dir.join("D15-toolpath-parameters.md"));
    let d15b = read(&dir.join("D15b-toolpath-parameters-2.md"));
    let mut common = BTreeMap::new();
    let upto = d15.find("\n## 3. ").unwrap_or(d15.len());
    for r in table_rows(&d15[..upto]) {
        let group = if r.heading.contains("tool_params") {
            "tool_params"
        } else if r.heading.contains("Geometry") || r.heading.contains("2.3.2") {
            "geometry"
        } else if r.heading.contains("Heights") {
            "heights"
        } else if r.heading.contains("Passes") {
            "passes"
        } else if r.heading.contains("Linking") {
            "linking"
        } else {
            continue;
        };
        if let Some(k) = r.cells.first() {
            common.entry((group.to_owned(), unbacktick(k))).or_insert(r);
        }
    }
    Docs { d15, d15b, common }
}

impl Docs {
    fn section(&self, t: ToolpathTypeId) -> Option<&str> {
        type_section(&self.d15, t.as_str()).or_else(|| type_section(&self.d15b, t.as_str()))
    }

    /// The range and dependencies the design gives for a field.
    fn note(&self, t: ToolpathTypeId, group: Group, path: &str) -> Option<String> {
        let own = self
            .section(t)
            .map(table_rows)
            .unwrap_or_default()
            .into_iter()
            .find(|r| {
                r.header.first().is_some_and(|h| h == "Key")
                    && r.cells.first().is_some_and(|k| unbacktick(k) == path)
            });
        let row = own.or_else(|| {
            self.common
                .get(&(group.key().to_owned(), path.to_owned()))
                .cloned()
        })?;
        let mut parts = Vec::new();
        if let Some(r) = row.get("Range").map(strip_refs).filter(|s| !s.is_empty()) {
            parts.push(format!("Allowed: {r}."));
        }
        if let Some(d) = row
            .get("Depends on")
            .map(strip_refs)
            .filter(|s| !s.is_empty() && s != "—")
        {
            parts.push(format!("Depends on: {d}."));
        }
        (!parts.is_empty()).then(|| parts.join(" "))
    }
}

fn type_page(t: ToolpathTypeId, cat: &BTreeMap<String, String>, tx: &Texts, d: &Docs) -> String {
    let label = cat
        .get(&format!("toolpath-type-{}", t.as_str()))
        .cloned()
        .unwrap_or_else(|| words(t.as_str()));
    let mut s = format!("{MARK}\n\n# {label}\n\n");
    s.push_str(&format!(
        "Type id `{}` · category: {} · runs in Setups of kind: {}\n\n",
        t.as_str(),
        category(t),
        setup_kinds(t)
    ));
    // The plain description if there is one, else the design's first paragraph.
    let plain = tx.description.get(t.as_str()).cloned();
    let text = plain.or_else(|| d.section(t).map(first_paragraph));
    if let Some(p) = text.filter(|p| !p.is_empty()) {
        s.push_str(&format!("{p}\n\n"));
    }
    s.push_str(&format!(
        "- Takes the material it cuts out of the stock for the toolpaths after it: {}.\n",
        if t.updates_stock() { "yes" } else { "no" }
    ));
    if t.follows_surface() {
        s.push_str("- Follows the surface of the model: stock to leave is measured along the surface normal.\n");
    }
    s.push_str("\nSee [Add a toolpath](Add-a-Toolpath) for how to add one, and the [list of toolpath types](Toolpath-Types).\n\n");
    s.push_str("In the project file a setting is written as `group.key`, for example `passes.stepover`. In the app the inspector shows each group on its own tab. Lengths are in millimetres in the file whatever unit the project shows.\n");
    for g in Group::ALL {
        let fields: Vec<&'static FieldMeta> = t.group_fields(g).collect();
        if fields.is_empty() {
            continue;
        }
        let gl = cat
            .get(&format!("group-{}", g.key()))
            .cloned()
            .unwrap_or_else(|| words(g.key()));
        s.push_str(&format!("\n## {gl}\n\n"));
        if g == Group::Heights {
            s.push_str(&format!(
                "A height is a reference plus an offset in mm, for example `{{ ref = \"stock_top\", offset = 5 }}`. The reference is one of {}.\n\n",
                HEIGHT_REFS
                    .iter()
                    .map(|x| format!("`{x}`"))
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
        }
        s.push_str(
            "| Setting | File key | Value | Default | What it does |\n|---|---|---|---|---|\n",
        );
        for (path, f) in flatten(&fields) {
            let label_id = f.label_id();
            let label = cat.get(&label_id).cloned().unwrap_or_else(|| words(f.key));
            let key = format!("{}.{}", g.key(), path);
            let help = tx
                .help
                .get(&format!("{}.{}", t.as_str(), key))
                .or_else(|| tx.help.get(&key))
                .cloned();
            let note = d.note(t, g, &path);
            let meaning = match (help, note) {
                (Some(h), Some(n)) => format!("{h} {n}"),
                (Some(h), None) => h,
                (None, Some(n)) => n,
                (None, None) => String::new(),
            };
            let default = if matches!(f.kind, FieldKind::Table(_)) {
                String::new()
            } else {
                default_text(f.default)
            };
            s.push_str(&format!(
                "| {} | `{}` | {} | {} | {} |\n",
                cell(&label),
                key,
                cell(&unit(f.kind)),
                cell(&default),
                cell(&meaning)
            ));
        }
    }
    s
}

fn index_page(cat: &BTreeMap<String, String>) -> String {
    let mut s = format!("{MARK}\n\n# Toolpath types\n\n");
    s.push_str("A toolpath is one cutting job with one tool: for example a pocket, a contour or a finishing pass over a 3-D surface. This page lists every type FluutCAM has. Each type has its own page with every setting, its unit and its default.\n\n");
    s.push_str("To add one to a Setup, see [Add a toolpath](Add-a-Toolpath). 3-D types do not need curves picked; 2-D types cut along curves or faces you select, which the app cannot pick yet (see [Known limits](Known-Limits)).\n\n");
    for c in [
        "2-D",
        "Holes",
        "3-D roughing",
        "3-D finishing",
        "Rotary",
        "Utility",
    ] {
        s.push_str(&format!(
            "## {c}\n\n| Type | Id | Runs in | Page |\n|---|---|---|---|\n"
        ));
        for t in ToolpathTypeId::ALL
            .into_iter()
            .filter(|t| category(*t) == c)
        {
            let label = cat
                .get(&format!("toolpath-type-{}", t.as_str()))
                .cloned()
                .unwrap_or_else(|| words(t.as_str()));
            s.push_str(&format!(
                "| {label} | `{}` | {} Setups | [{label}]({}) |\n",
                t.as_str(),
                setup_kinds(t).replace(", ", " and "),
                page_name(t)
            ));
        }
        s.push('\n');
    }
    s
}

// ── Diagnostics ──────────────────────────────────────────────────────

#[derive(Clone, Debug, Default, PartialEq)]
struct Found {
    code: String,
    /// `Some(true)` error, `Some(false)` warning.
    error: Option<bool>,
    message: Option<String>,
}

/// String literals of Rust source: `(start, end, text)`. Comments are
/// skipped; escapes `\"`, `\\` and `\n` are resolved.
fn literals(src: &str) -> Vec<(usize, usize, String)> {
    let b = src.as_bytes();
    let mut out = Vec::new();
    let mut i = 0;
    while i < b.len() {
        match b[i] {
            b'/' if b.get(i + 1) == Some(&b'/') => {
                while i < b.len() && b[i] != b'\n' {
                    i += 1;
                }
            }
            b'\'' => {
                // A char literal `'"'` must not open a string; a lifetime has no closing quote.
                if b.get(i + 2) == Some(&b'\'') {
                    i += 3;
                } else if b.get(i + 1) == Some(&b'\\') && b.get(i + 3) == Some(&b'\'') {
                    i += 4;
                } else {
                    i += 1;
                }
            }
            b'"' => {
                let start = i;
                i += 1;
                let mut text = Vec::new();
                while i < b.len() && b[i] != b'"' {
                    if b[i] == b'\\' && i + 1 < b.len() {
                        i += 1;
                        match b[i] {
                            b'n' => text.push(b' '),
                            b'\n' => {
                                while i + 1 < b.len() && b[i + 1].is_ascii_whitespace() {
                                    i += 1;
                                }
                            }
                            c => text.push(c),
                        }
                    } else {
                        text.push(b[i]);
                    }
                    i += 1;
                }
                out.push((start, i, String::from_utf8_lossy(&text).into_owned()));
                i += 1;
            }
            _ => i += 1,
        }
    }
    out
}

fn is_code(s: &str) -> bool {
    let mut parts = s.split('.');
    let first = parts.next().unwrap_or("");
    if !["param", "cam", "setup", "model", "sim", "post"].contains(&first) {
        return false;
    }
    s.contains('.')
        && s != "post.all"
        && s != "sim.{}"
        && s.chars().all(|c| {
            c.is_ascii_lowercase() || c.is_ascii_digit() || matches!(c, '_' | '.' | '{' | '}')
        })
}

/// Shows run-time parts of a code or message: `{ty}` in a code is the
/// type, any other `{...}` in a message is an ellipsis.
fn tidy_code(code: &str) -> String {
    let mut out = String::new();
    let mut rest = code;
    let mut n = 0;
    while let Some(i) = rest.find('{') {
        out.push_str(&rest[..i]);
        match rest[i..].find('}') {
            Some(j) => {
                out.push_str(if n == 0 { "<type>" } else { "<setting>" });
                n += 1;
                rest = &rest[i + j + 1..];
            }
            None => {
                rest = &rest[i + 1..];
                break;
            }
        }
    }
    out.push_str(rest);
    out
}

fn tidy_message(m: &str) -> String {
    let mut out = String::new();
    let mut rest = m;
    while let Some(i) = rest.find('{') {
        if rest[i..].starts_with("{{") {
            out.push_str(&rest[..=i]);
            rest = &rest[i + 2..];
            continue;
        }
        out.push_str(&rest[..i]);
        match rest[i..].find('}') {
            Some(j) => {
                out.push('…');
                rest = &rest[i + j + 1..];
            }
            None => {
                rest = &rest[i + 1..];
                break;
            }
        }
    }
    out.push_str(rest);
    out.replace("}}", "}").replace("  ", " ")
}

/// Codes and messages of the `Diagnostic` constructor calls in one file.
fn scan_source(src: &str) -> Vec<Found> {
    let src = src.split("#[cfg(test)]").next().unwrap_or(src);
    let lits = literals(src);
    let mut out = Vec::new();
    for (n, (start, end, text)) in lits.iter().enumerate() {
        if !is_code(text) {
            continue;
        }
        let mut from = start.saturating_sub(100);
        while !src.is_char_boundary(from) {
            from += 1;
        }
        let before = &src[from..*start];
        let pos = |pats: &[&str]| pats.iter().filter_map(|p| before.rfind(p)).max();
        let w = pos(&["warning", "warn", ".w("]);
        let e = pos(&["error", "err(", "fail(", ".e("]);
        let error = match (e, w) {
            (Some(e), Some(w)) => Some(e > w),
            (Some(_), None) => Some(true),
            (None, Some(_)) => Some(false),
            (None, None) => None,
        };
        // The message is the next string with a space or a placeholder in
        // it, within the call (the field name of `.e(code, field, msg)`
        // comes first and has neither).
        let message = lits[n + 1..]
            .iter()
            .take(3)
            .take_while(|(s, _, _)| s - end < 400)
            .find(|(_, _, t)| (t.contains(' ') || t.contains('{')) && !is_code(t))
            .map(|(_, _, t)| tidy_message(t));
        out.push(Found {
            code: tidy_code(text),
            error,
            message,
        });
    }
    out
}

fn source_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(rd) = std::fs::read_dir(dir) else {
        return;
    };
    let mut entries: Vec<_> = rd.filter_map(Result::ok).collect();
    entries.sort_by_key(|e| e.file_name());
    for e in entries {
        let p = e.path();
        let name = e.file_name().to_string_lossy().into_owned();
        if p.is_dir() {
            if name != "tests" {
                source_files(&p, out);
            }
        } else if name.ends_with(".rs") && name != "tests.rs" {
            out.push(p);
        }
    }
}

/// Severity and rule of the codes in the design documents' `Code | Sev |
/// Rule` tables.
fn doc_codes() -> BTreeMap<String, (bool, String)> {
    let dir = root().join("docs/design");
    let mut out = BTreeMap::new();
    let mut files: Vec<_> = std::fs::read_dir(&dir)
        .expect("docs/design")
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|x| x == "md"))
        .collect();
    files.sort();
    for f in files {
        for r in table_rows(&read(&f)) {
            if r.header.first().map(String::as_str) != Some("Code") {
                continue;
            }
            let (Some(code), Some(sev), Some(rule)) = (r.get("Code"), r.get("Sev"), r.get("Rule"))
            else {
                continue;
            };
            let code = unbacktick(code);
            if !is_code(&code) || !(sev == "E" || sev == "W") {
                continue;
            }
            out.entry(code).or_insert((sev == "E", strip_refs(rule)));
        }
    }
    out
}

struct Diag {
    error: Option<bool>,
    message: String,
    rule: String,
}

fn diagnostics(cat: &BTreeMap<String, String>) -> BTreeMap<String, Diag> {
    let mut found: BTreeMap<String, Found> = BTreeMap::new();
    let mut files = Vec::new();
    let crates = root().join("crates");
    let mut dirs: Vec<_> = std::fs::read_dir(&crates)
        .expect("crates")
        .filter_map(Result::ok)
        .map(|e| e.path())
        .collect();
    dirs.sort();
    for d in dirs {
        source_files(&d.join("src"), &mut files);
    }
    for f in files {
        for x in scan_source(&read(&f)) {
            let e = found.entry(x.code.clone()).or_insert_with(|| x.clone());
            if e.message.is_none() {
                e.message = x.message;
            }
            if e.error.is_none() {
                e.error = x.error;
            }
        }
    }
    let docs = doc_codes();
    let mut out = BTreeMap::new();
    for (code, f) in &found {
        out.insert(
            code.clone(),
            Diag {
                error: docs.get(code).map(|d| d.0).or(f.error),
                message: f.message.clone().unwrap_or_default(),
                rule: docs.get(code).map(|d| d.1.clone()).unwrap_or_default(),
            },
        );
    }
    for (code, (error, rule)) in docs {
        out.entry(code).or_insert(Diag {
            error: Some(error),
            message: String::new(),
            rule,
        });
    }
    for (code, d) in &mut out {
        // A message of the catalog is what the app shows.
        if let Some(m) = cat.get(&code.replace('.', "-")) {
            d.message.clone_from(m);
        }
    }
    out
}

fn diagnostics_page(cat: &BTreeMap<String, String>, tx: &Texts) -> String {
    let all = diagnostics(cat);
    let mut s = format!("{MARK}\n\n# Diagnostics\n\n");
    s.push_str("FluutCAM reports a problem as a diagnostic: a message with a code. An **error** stops a toolpath from calculating until you fix it. A **warning** lets the calculation run and tells you about something to check. The app shows diagnostics in the Messages tab, next to the setting they are about in the inspector, and in the status bar. The command line prints them as `error [t1] code: message` or `warning [t1] code: message`, where `t1` is the toolpath id.\n\n");
    s.push_str("The message in your window may fill in numbers and names where this page shows `…`. A code with `<type>` appears once for each toolpath type, with the type id in its place. See [Troubleshooting](Troubleshooting) for the problems you are most likely to meet first.\n\n");
    let mut groups: BTreeMap<&str, Vec<(&String, &Diag)>> = BTreeMap::new();
    for (c, d) in &all {
        let g = c.split('.').next().unwrap_or("");
        groups.entry(g).or_default().push((c, d));
    }
    let titles = [
        ("param", "Settings (`param`)"),
        ("cam", "Calculation (`cam`)"),
        ("setup", "Setups (`setup`)"),
        ("model", "Project and model files (`model`)"),
        ("sim", "Simulation (`sim`)"),
        ("post", "Posting (`post`)"),
    ];
    for (g, title) in titles {
        let Some(items) = groups.get(g) else {
            continue;
        };
        s.push_str(&format!("## {title}\n\n| Code | Kind | Message | What it means and what to do |\n|---|---|---|---|\n"));
        for (c, d) in items {
            let kind = match d.error {
                Some(true) => "error",
                Some(false) => "warning",
                None => "error or warning",
            };
            let advice = tx.advice_for(c).map(str::to_owned);
            let todo = match (advice, d.rule.as_str()) {
                (Some(a), "") => a,
                (Some(a), r) => format!("{a} Rule: {r}"),
                (None, "") => String::new(),
                (None, r) => r.to_owned(),
            };
            s.push_str(&format!(
                "| `{c}` | {kind} | {} | {} |\n",
                cell(&d.message),
                cell(&todo)
            ));
        }
        s.push('\n');
    }
    s
}

