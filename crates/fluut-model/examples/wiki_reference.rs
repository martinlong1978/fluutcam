fn pages() -> BTreeMap<String, String> {
    let cat = catalog();
    let tx = texts();
    let d = docs();
    let mut out = BTreeMap::new();
    out.insert("Toolpath-Types.md".to_owned(), index_page(&cat));
    for t in ToolpathTypeId::ALL {
        out.insert(format!("{}.md", page_name(t)), type_page(t, &cat, &tx, &d));
    }
    out.insert("Diagnostics.md".to_owned(), diagnostics_page(&cat, &tx));
    // Settings without help text, for whoever writes `help.toml` next.
    let mut missing = std::collections::BTreeSet::new();
    for t in ToolpathTypeId::ALL {
        for g in Group::ALL {
            let fields: Vec<&'static FieldMeta> = t.group_fields(g).collect();
            for (path, f) in flatten(&fields) {
                if matches!(f.kind, FieldKind::Table(_)) {
                    continue;
                }
                let key = format!("{}.{}", g.key(), path);
                if !tx.help.contains_key(&key)
                    && !tx.help.contains_key(&format!("{}.{key}", t.as_str()))
                {
                    missing.insert(key);
                }
            }
        }
    }
    if !missing.is_empty() {
        eprintln!(
            "wiki-reference: {} settings have no text in help.toml (their pages show the design's range instead): {}",
            missing.len(),
            missing.iter().cloned().collect::<Vec<_>>().join(", ")
        );
    }
    out
}

fn main() {
    let mut check = false;
    let mut dir = root().join("docs/wiki");
    let mut args = std::env::args().skip(1);
    while let Some(a) = args.next() {
        match a.as_str() {
            "--check" => check = true,
            "--out" => dir = PathBuf::from(args.next().expect("--out needs a folder")),
            other => {
                eprintln!("usage: wiki_reference [--check] [--out <folder>] (not {other})");
                std::process::exit(2);
            }
        }
    }
    let pages = pages();
    if check {
        let mut stale = Vec::new();
        for (name, text) in &pages {
            // A Windows checkout may have turned the line ends into CRLF.
            let on_disk = std::fs::read_to_string(dir.join(name))
                .ok()
                .map(|t| t.replace("\r\n", "\n"));
            if on_disk.as_deref() != Some(text.as_str()) {
                stale.push(name.clone());
            }
        }
        // A generated page that is no longer produced.
        if let Ok(rd) = std::fs::read_dir(&dir) {
            for e in rd.filter_map(Result::ok) {
                let name = e.file_name().to_string_lossy().into_owned();
                if name.ends_with(".md")
                    && !pages.contains_key(&name)
                    && std::fs::read_to_string(e.path()).is_ok_and(|t| t.starts_with(MARK))
                {
                    stale.push(format!("{name} (no longer generated)"));
                }
            }
        }
        if stale.is_empty() {
            println!("wiki-reference: {} pages are up to date", pages.len());
        } else {
            eprintln!(
                "wiki-reference: out of date: {}\nRun `cargo xtask wiki-reference` and commit the result.",
                stale.join(", ")
            );
            std::process::exit(1);
        }
    } else {
        std::fs::create_dir_all(&dir).expect("create the output folder");
        for (name, text) in &pages {
            std::fs::write(dir.join(name), text).expect("write a page");
        }
        println!(
            "wiki-reference: wrote {} pages to {}",
            pages.len(),
            dir.display()
        );
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn scans_a_plain_call() {
        let f = scan_source(
            r#"fn f() { Diagnostic::warning("cam.x.empty", format!("nothing at {id} here")) }"#,
        );
        assert_eq!(
            f,
            vec![Found {
                code: "cam.x.empty".into(),
                error: Some(false),
                message: Some("nothing at … here".into())
            }]
        );
    }

    #[test]
    fn scans_a_helper_with_a_field_argument() {
        let f = scan_source(
            r#"self.e("param.type.setup_kind", "type", format!("{} runs only in rotary Setups", ty))"#,
        );
        assert_eq!(f[0].code, "param.type.setup_kind");
        assert_eq!(f[0].error, Some(true));
        assert_eq!(
            f[0].message.as_deref(),
            Some("… runs only in rotary Setups")
        );
    }

    #[test]
    fn a_run_time_type_in_a_code_is_named() {
        let f = scan_source(
            r#"Diagnostic::error(&format!("cam.{ty}.tool_shape"), "needs a ball tool")"#,
        );
        assert_eq!(f[0].code, "cam.<type>.tool_shape");
    }

    #[test]
    fn ignores_test_code_comments_and_expression_names() {
        assert!(
            scan_source("// \"cam.a.b\"\nfn f() {}\n#[cfg(test)]\nmod t { \"cam.c.d\" }")
                .is_empty()
        );
        assert!(scan_source(r#"x("tool.diameter"); y("post.all")"#).is_empty());
    }

    #[test]
    fn a_char_literal_quote_does_not_open_a_string() {
        let f = scan_source(r#"let q = '"'; Diagnostic::error("cam.a.b", "text with space")"#);
        assert_eq!(f.len(), 1);
    }

    #[test]
    fn reads_tables_and_sections() {
        let md = "## 1. x\n\n### 2.1 `face`\n\nClears the top. [S 03 §3.10.4] More (D09 §2.1) text.\n\n| Key | Range | Depends on |\n|---|---|---|\n| `stepover` | (0, D] | tool |\n\n### 2.2 `other`\n\nNo.\n";
        let s = type_section(md, "face").unwrap();
        assert!(!s.contains("No."));
        assert_eq!(first_paragraph(s), "Clears the top. More text.");
        let rows = table_rows(s);
        assert_eq!(rows.len(), 1);
        assert_eq!(rows[0].get("Range"), Some("(0, D]"));
    }

    #[test]
    fn references_are_stripped_but_other_brackets_stay() {
        assert_eq!(strip_refs("a [S 02 §2.1] b (D15 §1) c (d)"), "a b c (d)");
    }
}
